# ---------------------------------------------------------------------

if run_clicked:
    clean_question = question.strip()

    if not clean_question:
        st.error("Enter a learner question.")
    else:
        try:
            with st.spinner(
                "Running the agentic tutoring workflow..."
            ):
                response = (
                    AgenticCoreService()
                    .handle_request(
                        {
                            "request_type":
                                "personalized_tutoring",
                            "query": clean_question,
                            "learner_id": "demo_user",
                            "metadata": {
                                "source":
                                    "lightweight_demo_interface",
                                "force_recovery_test":
                                    force_recovery,
                            },
                        }
                    )
                )

                trace = load_trace(
                    response.get("trace_path")
                )

            st.session_state["demo_response"] = response
            st.session_state["demo_trace"] = trace

        except LLMProviderUnavailableError as error:
            st.error(
                f"LLM provider unavailable: {error}"
            )

        except ValueError as error:
            st.error(str(error))

        except Exception as error:
            st.error(
                f"Workflow execution failed: {error}"
            )


