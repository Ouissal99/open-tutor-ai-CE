def render_manager_workflow() -> None:
    """Display the conceptual manager order used in the thesis."""

    first_row = st.columns(4)

    first_row[0].markdown(
        "**1. Task & Context Analyzer**"
    )
    first_row[1].markdown(
        "**2. Context Collector**"
    )
    first_row[2].markdown(
        "**3. Tool-Use Planner**"
    )
    first_row[3].markdown(
        "**4. Adaptive Tool Selector**"
    )

    second_row = st.columns(3)

    second_row[0].markdown(
        "**5. Tool Executor**"
    )
    second_row[1].markdown(
        "**6. Output Validator**"
    )
    second_row[2].markdown(
        "**7. Output Package Builder**"
    )


def format_optional_value(value: Any) -> str:
    """Return a readable value for optional trace fields."""

    if value is None or value == "":
        return "N/A"

    return str(value)


