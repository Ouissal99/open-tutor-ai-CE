def load_trace(trace_path_value: Any) -> Dict[str, Any]:
    """Load the Tool Interaction Trace generated by the workflow."""

    if not trace_path_value:
        return {}

    trace_path = Path(str(trace_path_value))

    if not trace_path.is_absolute():
        trace_path = REPO_ROOT / trace_path

    if not trace_path.exists() or not trace_path.is_file():
        return {}

    try:
        trace = json.loads(
            trace_path.read_text(encoding="utf-8")
        )
    except (OSError, json.JSONDecodeError):
        return {}

    return trace if isinstance(trace, dict) else {}


def collect_tools(
    response: Dict[str, Any],
    trace: Dict[str, Any],
) -> List[str]:
    """Collect tools used across all tutoring workflow rounds."""

    tools: List[str] = []

    scratchpad = response.get("scratchpad", [])

    if isinstance(scratchpad, list):
        for round_item in scratchpad:
            if not isinstance(round_item, dict):
                continue

            package = round_item.get("output_package", {}) or {}

            if not isinstance(package, dict):
                continue

            metadata = package.get("metadata", {}) or {}

            if not isinstance(metadata, dict):
                continue

            tool_names = metadata.get("tool_names", [])

            if not isinstance(tool_names, list):
                continue

            for tool_name in tool_names:
                if (
                    isinstance(tool_name, str)
                    and tool_name not in tools
                ):
                    tools.append(tool_name)

    if tools:
        return tools

    tool_selection = trace.get("tool_selection", {}) or {}

    if isinstance(tool_selection, dict):
        selected_tools = tool_selection.get(
            "selected_tools",
            [],
        )

        if isinstance(selected_tools, list):
            for tool_name in selected_tools:
                if (
                    isinstance(tool_name, str)
                    and tool_name not in tools
                ):
                    tools.append(tool_name)

    return tools


def build_trace_preview(
    response: Dict[str, Any],
    trace: Dict[str, Any],
    tools: List[str],
) -> Dict[str, Any]:
    """Build a compact trace preview for the demonstration."""

    validation = trace.get("validation_report", {}) or {}
    context = trace.get("collected_context_summary", {}) or {}
    memory_update = trace.get("memory_update_summary", {}) or {}

    if not isinstance(validation, dict):
        validation = {}

    if not isinstance(context, dict):
        context = {}

    if not isinstance(memory_update, dict):
        memory_update = {}

    return {
        "trace_id": (
            trace.get("trace_id")
            or response.get("trace_id")
        ),
        "task_type": trace.get("task_type"),
        "workflow_status": response.get("status"),
        "selected_tools": tools,
        "selection_strategy": trace.get(
            "selection_strategy"
        ),
        "reference_trace_id": trace.get(
            "reference_trace_id"
        ),
        "validation": {
            "status": validation.get("status"),
            "confidence_score": validation.get(
                "confidence_score"
            ),
            "failure_reason": validation.get(
                "failure_reason"
            ),
        },
        "attempts": trace.get(
            "attempts",
            response.get("attempts", 1),
        ),
        "recovery_used": trace.get(
            "recovery_used",
            response.get("recovery_used", False),
        ),
        "learner_context": {
            "learner_level": context.get(
                "learner_level"
            ),
            "is_weak_topic": context.get(
                "is_weak_topic"
            ),
            "retrieved_knowledge_chunks": context.get(
                "retrieved_knowledge_chunks"
            ),
        },
        "memory_update": {
            "status": trace.get(
                "memory_update_status"
            ),
            "diagnosed_gap": memory_update.get(
                "diagnosed_gap"
            ),
            "recommended_strategy": memory_update.get(
                "recommended_future_strategy"
            ),
        },
        "final_answer_status": trace.get(
            "final_answer_status"
        ),
    }


